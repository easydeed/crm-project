import { randomUUID } from 'node:crypto'
import { expect, test, type Page } from '@playwright/test'
import { expectCleanLayout } from './checks'

async function newDemoAccount(page: Page) {
  const email = `browser-${randomUUID()}@example.com`
  const password = 'browser-audit-password'
  await page.context().clearCookies()
  await page.goto('/register')
  await page.getByLabel('Name', { exact: true }).fill('Browser Audit')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByLabel('Phone', { exact: true }).fill('9095550147')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Demo checkout' })).toBeVisible()
  await expect(page.getByText('No payment is collected.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Activate demo plan' }).click()
  await expect(page).toHaveURL(/\/app\/start/)
  return { email, password }
}

test('demo signup, phone verification, paid switch, cancellation, and resume work through forms', async ({ page }) => {
  await newDemoAccount(page)
  await page.goto('/app/settings#phone')
  const phone = page.locator('#phone')
  await phone.getByRole('button', { name: 'Text me a code' }).click()
  const status = phone.getByRole('status')
  await expect(status).toContainText('Demo code:')
  const code = (await status.innerText()).match(/Demo code: (\d{6})/)![1]
  await phone.getByLabel('Code', { exact: true }).fill(code)
  await phone.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(phone).toContainText('is verified for texts')
  await page.goto('/app/addons')
  const toggle = page.getByRole('switch', { name: 'Text me the call list' })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await page.goto('/app/settings/billing')
  await expect(page.getByText('$21 including enabled extras')).toBeVisible()
  await page.reload()
  await expect(page.getByText('$21 including enabled extras')).toBeVisible()
  await page.getByRole('link', { name: 'Cancel my plan', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel my plan', exact: true }).click()
  await expect(page).toHaveURL(/done=canceled$/)
  await expect(page.getByRole('button', { name: 'Keep my plan' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Keep my plan' }).click()
  await expect(page).toHaveURL(/done=resumed$/)
  await expect(page.getByRole('link', { name: 'Cancel my plan', exact: true })).toBeVisible()
  await expectCleanLayout(page, { tapTargets: false, screen: 'audit-billing' })
})

test('imports, optional email edits, hidden selections, mid-queue navigation, and final Undo work', async ({ page }) => {
  await newDemoAccount(page)
  const suffix = randomUUID()
  await page.goto('/app/people/import')
  await page.getByRole('tab', { name: 'Paste a list' }).click()
  await page.getByRole('textbox').fill(`Name,Email,Address,Phone\nAudit First,first-${suffix}@example.com,"1142 Oakdale Ave, La Verne, CA 91750",9095550123\nAudit Second,second-${suffix}@example.com,"PO Box 14, La Verne, CA 91750",\nAudit Third,third-${suffix}@example.com,"PO Box 16, La Verne, CA 91750",`)
  await expect(page.getByRole('button', { name: 'Import', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  await expect(page.getByRole('heading', { name: '3 people are in.' })).toBeVisible()
  await page.getByRole('link', { name: 'Go to your people' }).click()
  const thirdPath = await page.getByRole('link', { name: 'Audit Third', exact: true }).getAttribute('href')
  await page.getByRole('checkbox', { name: 'Select Audit First', exact: true }).check()
  await expect(page.getByText('1 person selected', { exact: true })).toBeVisible()
  await page.getByRole('searchbox').fill('Audit Second')
  await expect(page.getByText('1 person selected', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Delete', exact: true })).toHaveCount(0)
  await page.getByRole('searchbox').fill('Audit First')
  await page.getByRole('link', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill('')
  await page.getByLabel('Notes', { exact: true }).fill('Email deliberately absent')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Saved.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Notes', { exact: true })).toHaveValue('Email deliberately absent')
  const thirdId = thirdPath!.split('/').at(-1)
  await page.goto(`/app/people/review?contact=${thirdId}`)
  await expect(page.getByText('Audit Third', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Leave them out' }).click()
  // The canonical Oakdale address is ambiguous in this fixture, so First also
  // needs review. Starting at Third must wrap through both earlier people.
  await expect(page.getByText('Audit First', { exact: true })).toBeVisible()
  const none = page.getByRole('button', { name: 'None of these', exact: true })
  if (await none.isVisible()) await none.click()
  await page.getByRole('button', { name: 'Leave them out' }).click()
  await expect(page.getByText('Audit Second', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Leave them out' }).click()
  await expect(page.getByRole('link', { name: 'Back to your people' })).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByText('Audit Second', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Leave them out' })).toBeVisible()
})

test('a real browser can recover a demo password and old sessions stop working', async ({ page, browser }) => {
  const account = await newDemoAccount(page)
  const oldSession = await page.context().storageState()
  await page.goto('/forgot-password')
  await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByRole('button', { name: 'Request reset link' }).click()
  await page.getByRole('link', { name: 'Open demo reset link' }).click()
  await page.getByLabel('New password', { exact: true }).fill('a-new-browser-password')
  await page.getByRole('button', { name: 'Save password' }).click()
  await expect(page.getByText('Password changed.', { exact: false })).toBeVisible()
  const stale = await browser.newContext({ storageState: oldSession })
  const stalePage = await stale.newPage()
  await stalePage.goto('http://localhost:3100/app')
  await expect(stalePage).toHaveURL(/\/login/)
  await stale.close()
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByLabel('Password', { exact: true }).fill('a-new-browser-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/app$/)
})
